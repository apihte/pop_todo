import { afterEach, expect, it, vi } from 'vitest';
import { cleanup, render, waitFor } from '@testing-library/svelte';
import userEvent from '@testing-library/user-event';
import { deadlineFromLocal } from '../src/lib/deadline';

vi.mock('@tauri-apps/api/core', () => ({ isTauri: () => false, invoke: vi.fn() }));
import App from '../src/App.svelte';

afterEach(cleanup);
it('runs the complete preview flow and restores todos after remount', async () => {
  localStorage.clear();
  const user = userEvent.setup();
  let view = render(App);
  await user.click(view.getByRole('button', { name: '展开代办列表' }));
  await waitFor(() => expect(view.getByRole('button', { name: /新增代办/ }).hasAttribute('disabled')).toBe(false));
  await user.click(view.getByRole('button', { name: /新增代办/ }));
  expect(view.getByRole('dialog', { name: '新增代办' })).toBeTruthy();
  await user.type(view.getByLabelText('标题'), '集成测试事件');
  await user.click(view.getByRole('button', { name: '保存' }));
  await waitFor(() => expect(view.queryByRole('dialog')).toBeNull());
  expect(view.getByText('集成测试事件')).toBeTruthy();
  expect(view.getByText(/1 件未完成/)).toBeTruthy();
  await user.click(view.getByRole('button', { name: '编辑“集成测试事件”' }));
  await user.clear(view.getByLabelText('标题'));
  await user.type(view.getByLabelText('标题'), '编辑后的事件');
  await user.type(view.getByLabelText('具体内容（选填）'), '具体内容{Enter}第二行');
  const { fireEvent } = await import('@testing-library/svelte');
  await fireEvent.input(view.getByLabelText('截止时间（选填）'), { target: { value: '2026-06-15T14:30' } });
  await user.click(view.getByRole('button', { name: '保存' }));
  await waitFor(() => expect(view.queryByRole('dialog')).toBeNull());
  expect(view.getByText('编辑后的事件')).toBeTruthy();
  expect(view.getByText(/1 件未完成/)).toBeTruthy();
  await user.click(view.getByRole('checkbox'));
  await waitFor(() => expect(view.getByText(/0 件未完成/)).toBeTruthy());
  await user.click(view.getAllByRole('button', { name: '收起代办列表' })[0]);
  expect(view.getByRole('button', { name: '展开代办列表' })).toBeTruthy();
  view.unmount();
  view = render(App);
  await user.click(view.getByRole('button', { name: '展开代办列表' }));
  await waitFor(() => expect((view.getByRole('checkbox') as HTMLInputElement).checked).toBe(true));
  await user.click(view.getByRole('button', { name: '编辑“编辑后的事件”' }));
  expect((view.getByLabelText('具体内容（选填）') as HTMLTextAreaElement).value).toBe('具体内容\n第二行');
  expect((view.getByLabelText('截止时间（选填）') as HTMLInputElement).value).toBe('2026-06-15T14:30');
  expect(JSON.parse(localStorage.getItem('floating-todo-preview-v1')!).todos[0].deadline).toBe(deadlineFromLocal('2026-06-15T14:30'));
  await user.clear(view.getByLabelText('标题'));
  await user.type(view.getByLabelText('标题'), '不保存的草稿');
  await user.keyboard('{Escape}');
  expect(view.queryByRole('dialog')).toBeNull();
  expect(view.getByText('编辑后的事件')).toBeTruthy();
  await user.click(view.getByRole('button', { name: /移除/ }));
  await waitFor(() => expect(view.queryByText('编辑后的事件')).toBeNull());
});
